import { Request, Response } from "express";
import Pet from "../models/pet.model";
import PetOrder from "../models/pet-order.model";
import User from "../models/user.model";
import { generatePDF } from "../services/pdf-generator.service";

export const generatePetSalesReport = async (
  req: Request,
  res: Response
): Promise<void> => {
  try {

    if (req.user?.role !== "ADMIN") {
      res.status(403).json({
        success: false,
        message: "Only administrators can access pet sales reports",
      });
      return;
    }

    const admin = await User.findById(req.user.userId);

    if (!admin || !admin.isActive || admin.role !== "ADMIN") {
      res.status(403).json({
        success: false,
        message: "Active administrator account not found",
      });
      return;
    }

    const orders = await PetOrder.find({
      status: "APPROVED",
    }).sort({ updatedAt: -1 });

    if (orders.length === 0) {
      generatePDF(
        res,
        "PawPath-Pet-Sales-Report.pdf",
        "Pet Sales Report",
        [
          "## Sales Summary",
          "Total Pets Sold: 0",
          "Total Sales Value: LKR 0.00",
          "",
          "## Sales Details",
          "No approved pet sales records were found.",
        ]
      );
      return;
    }

    const petIds = orders.map((order) => order.petId);

    const pets = await Pet.find({
      _id: { $in: petIds },
    });

    const petMap = new Map(
      pets.map((pet) => [pet._id, pet])
    );

    let totalSalesValue = 0;

    const content: string[] = [];

    content.push("## Sales Summary");
    content.push(`Total Approved Orders: ${orders.length}`);
    content.push("");
    content.push("## Sales Details");

    orders.forEach((order, index) => {
      const pet = petMap.get(order.petId);

      if (!pet) {
        content.push("");
        content.push(`Order ${index + 1}: ${order.orderId}`);
        content.push("Pet Information: Not Available");
        content.push(`Customer: ${order.customerName}`);
        content.push("Price: Not Available");
        return;
      }

      const petPrice = Number(pet.price);

      totalSalesValue += petPrice;

      const saleDate = (order as any).updatedAt
        ? new Date((order as any).updatedAt).toLocaleDateString()
        : "Not Available";

      content.push("");
      content.push(`Order ${index + 1}: ${order.orderId}`);
      content.push(`Pet Name: ${pet.name}`);
      content.push(`Species: ${pet.species}`);
      content.push(`Breed: ${pet.breed || "Not Specified"}`);
      content.push(`Customer: ${order.customerName}`);
      content.push(`Customer Email: ${order.customerEmail}`);
      content.push(`Customer Phone: ${order.customerPhone}`);
      content.push(`Sale Date: ${saleDate}`);
      content.push(
        `Pet Price: LKR ${petPrice.toLocaleString("en-LK", {
          minimumFractionDigits: 2,
        })}`
      );
    });

    content.splice(
      2,
      0,
      `Total Sales Value: LKR ${totalSalesValue.toLocaleString("en-LK", {
        minimumFractionDigits: 2,
      })}`
    );

    content.push("");
    content.push("## Report Information");
    content.push("Report Type: Pet Sales Report");
    content.push("Order Status: APPROVED");
    content.push("Generated By: PawPath Administrator");

    generatePDF(
      res,
      "PawPath-Pet-Sales-Report.pdf",
      "Pet Sales Report",
      content
    );
  } catch (error) {
    console.error("Generate pet sales report error:", error);

    if (!res.headersSent) {
      res.status(500).json({
        success: false,
        message: "Failed to generate pet sales report",
      });
    }
  }
};
